// ============================================================
// Helper: Generate timestamps relative to "now"
// ============================================================
const now = new Date();

function daysAgo(days: number, hours = 0, minutes = 0): Date {
  const d = new Date(now);
  d.setDate(d.getDate() - days);
  d.setHours(hours, minutes, 0, 0);
  return d;
}

function todayAt(hours: number, minutes: number): Date {
  const d = new Date(now);
  d.setHours(hours, minutes, 0, 0);
  return d;
}

function yesterdayAt(hours: number, minutes: number): Date {
  return daysAgo(1, hours, minutes);
}

